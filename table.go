package refbench

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// Table renders docs/perf-table.md from a report. It is a pure function of the
// report's content, so the CI mode can check that the file has no hand edits.
func Table(r *Report) []byte {
	r.Finish()
	var b bytes.Buffer
	b.WriteString("# Performance table\n\n")
	b.WriteString("<!-- Generated by refbench from docs/perf.json. Do not edit. -->\n\n")
	fmt.Fprintf(&b, "- Date: %s\n- Commit: %s\n- Go: %s\n- Machine: %s\n", r.Date, r.Commit, r.Go, r.Machine)
	keys := make([]string, 0, len(r.RefVersions))
	for k := range r.RefVersions {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "- %s: %s\n", k, r.RefVersions[k])
	}
	switch r.Status {
	case StatusDeferred:
		b.WriteString("- Timing: **deferred** (no verdict; allocation counts only)\n")
	case StatusMeasured:
		fmt.Fprintf(&b, "- Load (1 min) over the rounds: min %.2f, median %.2f, max %.2f; gate %.2f\n",
			r.Load.Min, r.Load.Median, r.Load.Max, r.MaxLoad)
		if r.Valid {
			b.WriteString("- Run: valid (every round under the gate)\n")
		} else {
			b.WriteString("- Run: **invalid** (a round ended above the gate; no verdict)\n")
		}
	}
	b.WriteString("\nns/call, median [first quartile, third quartile]; ratio = Go / reference.\n\n")
	b.WriteString("| case | function | reference | Go | reference | ratio | verdict | parity | allocs |\n")
	b.WriteString("|---|---|---|---:|---:|---:|---|---|---:|\n")
	for _, row := range r.Rows {
		goCell, refCell, ratio, verdict := "—", "—", "—", "deferred"
		if len(row.Rounds) > 0 {
			goCell, refCell = cell(row.Go), cell(row.Ref)
			ratio = fmt.Sprintf("%.2f", row.Ratio)
			verdict = row.Verdict
			if !r.Valid {
				verdict = "invalid"
			}
		}
		fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s | %s | %s | %s | %g |\n",
			esc(row.Name), row.Func, esc(row.Reference), goCell, refCell, ratio, verdict, row.Parity, row.Allocs)
	}
	return b.Bytes()
}

func cell(s Summary) string {
	return fmt.Sprintf("%.4g [%.4g, %.4g]", s.Median, s.Q1, s.Q3)
}

func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
